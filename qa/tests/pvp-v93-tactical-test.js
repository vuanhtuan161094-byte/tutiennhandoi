import { buildRegistry } from '../../dist/content/registry.js';
import { createPlayableAdventureState, playablePlayerProfile } from '../../dist/content/adventure.js';
import { adventureEnemies, lightningSwordCultivator } from '../../dist/content/entities.js';
import { thanhHaWorld } from '../../dist/content/world.js';
import { SimulationSession } from '../../dist/core/session.js';
import { applyPvpTacticalPresetV93, pvpTacticalPresetsV93 } from '../../dist/core/pvp-v91.js';

let passed=0; const check=(ok,label)=>{if(!ok)throw new Error(`FAIL: ${label}`);passed++;console.log(`✓ ${label}`)};
const registry=buildRegistry(), now=1771000000000;
const presets=pvpTacticalPresetsV93();
check(presets.length===5,'exactly five Tactical presets');
check(presets.map(x=>x.id).join(',')==='balanced,tempo,stack,reserve,execute','canonical preset order');
const transformed=presets.map(x=>applyPvpTacticalPresetV93(lightningSwordCultivator,x.id,registry));
check(new Set(transformed.map(x=>x.pvpTacticalV93.rulesFingerprint)).size===5,'all five presets produce distinct aiProfile.rules fingerprints');
for(const e of transformed) check(e.aiProfile.rules.every(r=>(r.conditions??[]).length<=2),`${e.pvpTacticalV93.presetName}: AI rules stay within 2-condition contract`);
const stack=transformed.find(x=>x.pvpTacticalV93.presetId==='stack');
const baseSetup=lightningSwordCultivator.aiProfile.rules.find(x=>x.skillId==='skill.guide_thunder');
const stackSetup=stack.aiProfile.rules.find(x=>x.skillId==='skill.guide_thunder');
const stackBurst=stack.aiProfile.rules.find(x=>x.skillId==='skill.thunder_burst');
check(stackSetup.priority>baseSetup.priority,'Tích Thế raises Setup priority');
check(stackBurst.conditions.some(x=>x.type==='targetHpBelow'&&x.pct===55),'Tích Thế gates Burst at target HP <55%');
const reserve=transformed.find(x=>x.pvpTacticalV93.presetId==='reserve');
check(reserve.aiProfile.rules.find(x=>x.skillId==='skill.basic_strike').priority>lightningSwordCultivator.aiProfile.rules.find(x=>x.skillId==='skill.basic_strike').priority,'Giữ Chân Nguyên raises Basic priority');
const execute=transformed.find(x=>x.pvpTacticalV93.presetId==='execute');
check(execute.aiProfile.rules.find(x=>x.skillId==='skill.thunder_burst').conditions.some(x=>x.type==='targetHpBelow'&&x.pct===35),'Kết Liễu gates finisher at target HP <35%');

const state=createPlayableAdventureState();state.realm.maxRealmOrder=18;
const s=new SimulationSession(registry,thanhHaWorld,adventureEnemies,playablePlayerProfile,9300,state);s.joinPvpV91(now);
let view=s.pvpV91(now+1); const ticketIds=view.opponents.map(x=>x.id).join('|');
s.setPvpTacticalV94('stack',now+2);view=s.pvpV91(now+2);
check(view.tactical.selected.id==='stack','session persists selected Tactical preset');
check(view.opponents.map(x=>x.id).join('|')===ticketIds,'changing Tactical does not reroll tickets');
s.refreshPvpDefenseV91(now+3);view=s.pvpV91(now+3);
check(view.defense.tacticalPresetId==='stack','defense snapshot stores Tactical preset');
check(view.tactical.defensePresetId==='stack','view exposes defense Tactical snapshot');
const fight=s.challengePvpV91(view.opponents[0].id,now+4);
check(fight.tacticalPresetId==='stack','challenge reports applied Tactical preset');
const replayEntity=s.state.pvpV91.history[0].replay.playerEntity;
check(replayEntity.pvpTacticalV93?.presetId==='stack','CombatKernel input entity carries Tactical preset');
const expectedKernelEntity=applyPvpTacticalPresetV93(s.personalCombatEntity(),'stack',registry);
check(replayEntity.pvpTacticalV93.rulesFingerprint===expectedKernelEntity.pvpTacticalV93.rulesFingerprint&&JSON.stringify(replayEntity.aiProfile.rules)===JSON.stringify(expectedKernelEntity.aiProfile.rules),'CombatKernel input receives transformed aiProfile.rules');
const replay=s.replayPvpV91(fight.fightId);
check(replay.verified===true,'Tactical fight replay remains deterministic');
console.log(`\n${passed}/20 V93 Tactical checks passed.`);
